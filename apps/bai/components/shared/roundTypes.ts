/**
 * 各モジュールの「1問」をどの段階まで解かせるかの指定。
 *
 * 実際の単元テストは 1つの大問が「図をうめる → 式に表す → 計算して答える」のように
 * 技能ごとに分けて採点される（式は「計算の答えが誤っていても配点してよい」と明記）。
 * 練習では 'full' で通しで解き、本番テストモードでは技能ごとに1問ずつ出すために
 * 個別の focus を指定する。
 */
export type RoundFocus =
  | 'full'      // 通し（練習モード）
  | 'diagram'   // 図（テープ図・数直線）の□をうめる
  | 'relation'  // □を使ったかけ算の関係式に表す（□×5＝750）
  | 'shiki'     // 式を選ぶ
  | 'answer'    // 計算して答える
  | 'asview'    // 「◯を1とみると、△はいくつにあたるか」
  | 'diff'      // 差（ふえた量）を求める
  | 'judge';    // 割合で くらべて どちらかを 判断する
