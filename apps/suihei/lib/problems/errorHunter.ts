/* ============================ 組み立て ============================ */

/** 選択肢から太字（**）を外す。太字は画面で色がつくので、色だけで正解が分かってしまう */
const plain = (t: string) => t.replace(/\*\*/g, '');

function buildProblem(level: ErrorLevel, c: ErrorCase): GeoProblem {
  const kid = pick(KIDS);
  // ①まちがい発見: まちがい1つ＋正しい考え3つ
  const wrongOpts = shuffle([{ t: c.wrong, ok: true }, ...pickN(c.rights, 3).map((t) => ({ t, ok: false }))]);
  const wrongIndex = wrongOpts.findIndex((o) => o.ok);
  // ②修正
  const fixOpts = shuffle([{ t: c.fix, ok: true }, ...pickN(c.fixWrongs, 3).map((t) => ({ t, ok: false }))]);
  const fixIndex = fixOpts.findIndex((o) => o.ok);
  // ③理由
  const reasonOpts = shuffle([{ t: c.reason, ok: true }, ...pickN(c.reasonWrongs, 3).map((t) => ({ t, ok: false }))]);
  const reasonIndex = reasonOpts.findIndex((o) => o.ok);

  return {
    skillId: level,
    moduleId: 'error-hunter',
    prompt: `${kid}さんは、下の図について つぎのように 考えました。\n**まちがっている** 考えは どれですか。`,
    figure: c.figure(),
    answer: {
      kind: 'errorFix',
      wrongOptions: wrongOpts.map((o) => plain(o.t)),
      wrongIndex,
      fixChoices: fixOpts.map((o) => plain(o.t)),
      fixIndex,
      reasons: reasonOpts.map((o) => plain(o.t)),
      reasonIndex,
    },
    hints: [
      'まず 図を 見て、たしかめられる ことを 1つずつ 確認しよう。',
      'ことばの「じょうけん」（決め方）を 思い出して、図と 合っているかを 見る。',
      `${c.fix.replace(/\*\*/g, '')} が 正しいよ。`,
    ],
    explain: c.explain,
    label: `エラーハンター（${c.id}）`,
    signature: `eh:${c.id}:${wrongOpts.map((o) => o.t).join('|')}`,
  };
}

export function generateError(level: ErrorLevel): GeoProblem {
  const cases = level === 'eh-line' ? lineCases() : level === 'eh-quad' ? quadCases() : diagCases();
  return buildProblem(level, pick(cases));
}

/** 検証スクリプト用: そのレベルが扱う誤概念の一覧。 */
export function errorCaseIds(level: ErrorLevel): string[] {
  const cases = level === 'eh-line' ? lineCases() : level === 'eh-quad' ? quadCases() : diagCases();
  return cases.map((c) => c.id);
}
