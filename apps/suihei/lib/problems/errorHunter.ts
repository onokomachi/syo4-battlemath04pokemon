const rad = (d: number) => (d * Math.PI) / 180;

/** 傾いた2直線の図（垂直／平行／それ以外）をつくる。 */
function twoLines(baseDeg: number, deltaDeg: number, gap: number, extend = 0): FigureSpec {
  const u = { x: Math.cos(rad(baseDeg)), y: Math.sin(rad(baseDeg)) };
  const n = { x: -u.y, y: u.x };
  const c1 = { x: 30, y: 20 };
  const c2 = { x: c1.x + n.x * gap, y: c1.y + n.y * gap };
  const mk = (id: string, c: { x: number; y: number }, deg: number, label: string) => {
    const v = { x: Math.cos(rad(deg)), y: Math.sin(rad(deg)) };
    return { id, a: { x: c.x - v.x * 18, y: c.y - v.y * 18 }, b: { x: c.x + v.x * 18, y: c.y + v.y * 18 }, label, extend };
  };
  return { w: 62, h: 42, lines: [mk('a', c1, baseDeg, 'あ'), mk('b', c2, baseDeg + deltaDeg, 'い')] };
}

