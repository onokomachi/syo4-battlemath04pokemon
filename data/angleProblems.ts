interface TextExtra {
  svg?: string;
  options?: string[];
  multiple?: boolean;
  hint?: string | string[];
}

const t = (question: string, answer: string, extra?: TextExtra): Problem => ({
  type: 'text',
  data: { question, ...extra },
  answer,
});

