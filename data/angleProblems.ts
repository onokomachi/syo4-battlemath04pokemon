// ---- 三角じょうぎの角(2まいの角の知識+組み合わせ・重ね合わせ) ----
//
// 図(SVG)にも問題文にも「30°」のような具体的な数値は置かない。
// かわりに「細長いほうの いちばん小さい角」のように 角を名前で指し示し、
// 三角じょうぎ2まいの角(90°・60°・30° と 90°・45°・45°)を 覚えているかどうかを ためす。
// ヒントでは 2まいぶんの角の一覧(一般知識)までは 教えてよいが、
// この問題で どの2つを 使っているか・答えの数そのものは 教えない。
const JOUGI_SETS_HINT = '細長いほうの三角じょうぎは 90°・60°・30°、直角二等辺三角形のほうは 90°・45°・45°だよ。';

/** 角を名前で指し示す文言(数値は出さない) */
const refOf = (kind: JougiKind, corner: JougiCorner): string => {
  if (kind === 'long') {
    if (corner === 30) return '細長いほうの三角じょうぎの いちばん小さい角';
    if (corner === 60) return '細長いほうの三角じょうぎの 直角のつぎに大きい角';
    return '細長いほうの三角じょうぎの 直角';
  }
  return corner === 45 ? '直角二等辺三角形の三角じょうぎの角' : '直角二等辺三角形の三角じょうぎの 直角';
};

