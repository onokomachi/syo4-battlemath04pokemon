-- 町の「達成度」でバトルのスタミナを安くする（2026-11-11 先生と決めた）
--
-- きまり：ぼうけんのバトル1回のスタミナ（はじめは5）を、その町の単元の「練習の項目のうち熟達した割合」で決める。
--   100％ → 2、75％以上 → 3、50％以上 → 4、それより下 → 5。熟達＝5問れんぞくノーミス（skill_state.perfect_streak >= 5。町の解放の「練習」と同じ数え方）。
--   アプリの無い町（大きい数・折れ線グラフ・角）は 5 のまま。スピード・モンスター対戦・クラス対戦は 変えない。
--   決めるのはサーバ（sanmon_spend）。子どもの画面（SANMON）は 同じ数え方で「1回 n」を出す（kit の sanmonUnits の練習のメーター）。
-- 町 → 項目の表 sanmon_town_skill は kit のカタログ（SANMON_UNITS の appId・modules）から作った。
--   **カタログの項目を足したり名前を変えたりしたら、この表も作り直す**（SANMON の scripts/export-town-skills.mjs）。

